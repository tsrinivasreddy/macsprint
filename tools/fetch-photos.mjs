// Downloads free Unsplash photos (https://unsplash.com/license: free for commercial use,
// no permission or credit needed), resizes them to small thumbnails, and lists them in
// js/photos.js so every .ph thumbnail on the site shows a real photo.
// Needs images.unsplash.com allowed on the network. Run: node tools/fetch-photos.mjs
import { writeFileSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'assets', 'photos');
mkdirSync(dir, { recursive: true });

// [file name, Unsplash photo id, what it shows]
const PHOTOS = [
  ['beach', 'photo-1507525428034-b723cf961d3e', 'tropical beach'],
  ['mountains', 'photo-1506905925346-21bda4d32df4', 'mountain range'],
  ['lake', 'photo-1506744038136-46273834b3fb', 'mountain lake'],
  ['forest', 'photo-1441974231531-c6227db76b6e', 'forest light'],
  ['city', 'photo-1477959858617-67f85cf4f1df', 'city skyline'],
  ['skyline-night', 'photo-1480714378408-67cf0d13bc1b', 'city at night'],
  ['food', 'photo-1504674900247-0877df9cc836', 'plate of food'],
  ['coffee', 'photo-1495474472287-4d71bcdd2085', 'coffee cup'],
  ['friends', 'photo-1529156069898-49953e39b3ac', 'friends together'],
  ['family', 'photo-1511895426328-dc8714191300', 'family outdoors'],
  ['portrait', 'photo-1517841905240-472988babdf9', 'portrait'],
  ['concert', 'photo-1501386761578-eac5c94b800a', 'concert'],
  ['road-trip', 'photo-1469474968028-56623f02e42e', 'valley view'],
  ['sunset-hills', 'photo-1500530855697-b586d89ba3ee', 'sunset hills'],
  ['desk', 'photo-1499951360447-b19be8fe80f5', 'laptop on a desk'],
  ['night-sky', 'photo-1519681393784-d120267933ba', 'mountains under stars'],
];

const ok = [];
for (const [name, id, alt] of PHOTOS) {
  const url = `https://images.unsplash.com/${id}?w=640&q=72&fm=jpg&fit=crop&crop=entropy&ar=4:3`;
  const res = await fetch(url);
  if (!res.ok) { console.warn(`skip ${name}: ${res.status}`); continue; }
  const file = join(dir, `${name}.jpg`);
  writeFileSync(file, Buffer.from(await res.arrayBuffer()));
  ok.push([name, alt]);
  console.log('saved', name);
}
writeFileSync(join(root, 'js', 'photos.js'), `// Generated by tools/fetch-photos.mjs: free Unsplash photos in assets/photos/.\nexport const PHOTOS = ${JSON.stringify(ok.map(([n]) => `assets/photos/${n}.jpg`), null, 2)};\n`);
console.log(`${ok.length} photos ready`);
